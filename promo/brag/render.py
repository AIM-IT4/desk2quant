def frame_at(seconds: float) -> Image.Image:
    canvas = Image.new("RGB", (W, H), BG)
    if seconds < 3.6:
        first_scene(canvas, seconds)
    elif seconds < 8:
        second_scene(canvas, seconds - 3.6)
    elif seconds < 12.7:
        third_scene(canvas, seconds - 8)
    elif seconds < 17.2:
        fourth_scene(canvas, seconds - 12.7)
    else:
        fifth_scene(canvas, seconds - 17.2)
    return canvas


def make_audio(path: Path) -> None:
    rate = 44100
    length = DURATION * rate
    sound = np.zeros(length, dtype=np.float64)
    rng = np.random.default_rng(20260926)
    beat = 60 / 108
    chords = [(220, 261.63, 329.63), (174.61, 220, 261.63),
              (196, 261.63, 329.63), (196, 246.94, 293.66)]

    for bar in range(10):
        start = int(bar * 4 * beat * rate)
        if start >= length:
            break
        n = min(int(2.45 * rate), length - start)
        t = np.arange(n) / rate
        chord = chords[bar % 4]
        swell = np.minimum(t / .35, 1) * np.minimum((2.45 - t) / .55, 1)
        pad = sum(np.sin(2 * np.pi * f * t) +
                  .12 * np.sin(2 * np.pi * (f * 2.001) * t)
                  for f in chord) / 3
        sound[start:start+n] += .045 * pad * np.maximum(0, swell)
        bass = np.sin(2 * np.pi * (chord[0] / 2) * t)
        sound[start:start+n] += .042 * bass * np.exp(-t * 1.25)

    for k in range(math.ceil(DURATION / beat)):
        start = int(k * beat * rate)
        n = min(int(.22 * rate), length - start)
        if n <= 0:
            break
        t = np.arange(n) / rate
        phase = 2 * np.pi * (63 * t + 75 * (.05 / 4.5) *
                            (1 - np.exp(-t * 4.5)))
        sound[start:start+n] += .115 * np.sin(phase) * np.exp(-t * 19)
        if k % 2:
            noise = rng.standard_normal(n)
            high = np.r_[noise[0], np.diff(noise)]
            sound[start:start+n] += .014 * high * np.exp(-t * 45)
        else:
            sound[start:start+n] += .007 * np.sin(2 * np.pi * 1100 * t) * \
                np.exp(-t * 90)

    for scene_t in [0, 3.6, 8, 12.7, 17.2]:
        start = int(scene_t * rate)
        n = min(int(.28 * rate), length - start)
        t = np.arange(n) / rate
        tone = (np.sin(2 * np.pi * 440 * t) +
                .45 * np.sin(2 * np.pi * 660 * t))
        sound[start:start+n] += .031 * tone * np.exp(-t * 16)

    ramp = np.minimum(np.arange(length) / (.32 * rate), 1)
    fade = np.minimum((length - np.arange(length)) / (.9 * rate), 1)
    sound = np.tanh(sound * 1.8) * .72 * np.maximum(0, ramp) * \
        np.maximum(0, fade)
    pcm = np.clip(sound * 32767, -32768, 32767).astype("<i2")
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(rate)
        wav.writeframes(pcm.tobytes())


def run() -> None:
    if not shutil.which("ffmpeg"):
        raise RuntimeError("FFmpeg is required on PATH")
    WORK.mkdir(parents=True, exist_ok=True)
    # A settled real-product frame is both the poster and the first video frame.
    poster = frame_at(6.3)
    poster.save(OUT / "brag.jpg", quality=93, subsampling=0)
    make_audio(WORK / "original-soundtrack.wav")
    temp_video = WORK / "silent.mp4"
    command = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
               "-f", "rawvideo", "-pixel_format", "rgb24", "-video_size",
               f"{W}x{H}", "-framerate", str(FPS), "-i", "-",
               "-c:v", "libx264", "-preset", "fast", "-crf", "20",
               "-pix_fmt", "yuv420p", "-movflags", "+faststart",
               str(temp_video)]
    proc = subprocess.Popen(command, stdin=subprocess.PIPE)
    assert proc.stdin is not None
    try:
        for i in range(FPS * DURATION):
            frame = poster if i == 0 else frame_at(i / FPS)
            proc.stdin.write(frame.tobytes())
        proc.stdin.close()
    except BrokenPipeError as exc:
        raise RuntimeError("FFmpeg stopped during rendering") from exc
    if proc.wait():
        raise RuntimeError("Video encoding failed")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                    "-i", str(temp_video), "-i",
                    str(WORK / "original-soundtrack.wav"), "-c:v", "copy",
                    "-c:a", "aac", "-b:a", "160k", "-af",
                    "loudnorm=I=-20:TP=-1.5:LRA=11", "-shortest",
                    "-movflags", "+faststart", str(OUT / "brag.mp4")],
                   check=True)
    print(f"Created {OUT / 'brag.mp4'} and {OUT / 'brag.jpg'}")


if __name__ == "__main__":
    run()
