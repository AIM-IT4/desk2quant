def first_scene(canvas: Image.Image, local_t: float) -> None:
    paper(canvas)
    header(canvas)
    d = ImageDraw.Draw(canvas)
    enter = ease(local_t / .48)
    x = round(67 - (1 - enter) * 110)
    text(d, (x, 117), "// SIMULATED DESK INCIDENT", 20, MUTED, "mono")
    text(d, (x, 185), "THE NUMBERS", 67, INK)
    text(d, (x, 274), "DON'T MATCH.", 67, INK)
    d.rectangle((x + 1, 378,
                 x + 1 + round(530 * ease((local_t - .7) / .55)), 387),
                fill=TEAL)
    text(d, (x + 2, 444), "What would you test first?", 26, MUTED, "regular")
    text(d, (x + 2, 610), "EQUITY DERIVATIVES  /  P&L CONTROL", 17, MUTED,
         "mono")

    slide = 1 - ease((local_t - .13) / .64)
    right = round(1180 + 360 * slide)
    left = right - 430
    rounded(d, (left + 10, 125 + 10, right + 10, 605 + 10), TEAL, radius=5)
    rounded(d, (left, 125, right, 605), NAVY, outline=INK, width=3, radius=5)
    text(d, (left + 34, 157), "INCIDENT 01 / THE MISSING VEGA", 16,
         TEAL, "mono")
    d.line((left + 34, 198, right - 34, 198), fill=(62, 82, 86), width=2)
    numbers = [
        ("DESK ESTIMATE", "+$1.42m", WHITE),
        ("OFFICIAL P&L", "+$0.61m", WHITE),
        ("UNEXPLAINED", "−$0.81m", PINK),
    ]
    for i, (label, value, col) in enumerate(numbers):
        yy = 220 + i * 119
        a = ease((local_t - .52 - i * .17) / .4)
        if a > 0:
            text(d, (left + 36, yy), label, 16, TEAL, "mono")
            # Reveal the figure as the right-hand side of a masked scan.
            text(d, (left + 36, yy + 27), value, 43, col)
            cover_start = left + 36 + round(355 * a)
            if cover_start < right - 25:
                d.rectangle((cover_start, yy + 28, right - 26, yy + 86),
                            fill=NAVY)
        if i < 2:
            d.line((left + 35, yy + 106, right - 35, yy + 106),
                   fill=(58, 76, 80), width=1)


