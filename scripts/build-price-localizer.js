// Generates /price-localizer.js from the pricing core in script.js.
//
// script.js is ~270KB and renders whole pages, so static pages (the SEO product
// pages) and the bundle landing sections cannot load it just to show a price.
// This script copies the exact pricing functions (country detection, currency
// map, FX rates, PPP conversion, formatting) out of script.js and wraps them in
// a small self-contained file. Because it is extracted, not re-written, the
// displayed price can never drift from the price script.js shows and the server
// charges. test/price-localizer.test.mjs fails if the committed file is stale.
//
//   node scripts/build-price-localizer.js          # write price-localizer.js
//   node scripts/build-price-localizer.js --check  # exit 1 if it is out of date
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'script.js');
const OUT = path.join(ROOT, 'price-localizer.js');

// Returns the source of a top-level `[async ]function name(...) { ... }`, or of a
// `const NAME = { ... };`, found by brace matching (skipping strings/comments).
function extractBlock(src, startRegex) {
  const m = startRegex.exec(src);
  if (!m) throw new Error('price-localizer: could not find ' + startRegex);
  let i = src.indexOf('{', m.index + m[0].length - 1);
  const start = m.index;
  let depth = 0;
  for (; i < src.length; i++) {
    const c = src[i], n = src[i + 1];
    if (c === '/' && n === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && n === '*') { i = src.indexOf('*/', i) + 1; continue; }
    if (c === '"' || c === "'" || c === '`') {
      const q = c; i++;
      for (; i < src.length; i++) {
        if (src[i] === '\\') { i++; continue; }
        if (src[i] === q) break;
        if (q === '`' && src[i] === '$' && src[i + 1] === '{') {
          // nested template expression: skip to its matching brace
          let d = 1; i += 2;
          for (; i < src.length && d > 0; i++) { if (src[i] === '{') d++; else if (src[i] === '}') d--; }
          i--;
        }
      }
      continue;
    }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) { let end = i + 1; if (src[end] === ';') end++; return src.slice(start, end); } }
  }
  throw new Error('price-localizer: unbalanced braces for ' + startRegex);
}

function build() {
  const src = fs.readFileSync(SRC, 'utf8');
  const parts = [
    extractBlock(src, /const CURRENCY_MAP = \{/),
    extractBlock(src, /(?:async )?function getUserCountry\s*\(/),
    extractBlock(src, /(?:async )?function fetchExchangeRates\s*\(/),
    extractBlock(src, /(?:async )?function getFallbackRates\s*\(/),
    extractBlock(src, /(?:async )?function getCurrencyForCountry\s*\(/),
    extractBlock(src, /(?:async )?function convertPrice\s*\(/),
    extractBlock(src, /(?:async )?function formatPrice\s*\(/)
  ];
  const core = parts.join('\n\n');

  return `/* GENERATED by scripts/build-price-localizer.js from script.js - do not edit by hand.
 *
 * Shows INR prices in the visitor's local currency with the same PPP uplift the
 * checkout charges (1.6x strong currencies, 1.3x weaker economies). Loaded on
 * pages that do not load script.js (static SEO product pages, the bundle landing
 * sections, the homepage mentor card). India and unknown countries are left in
 * INR, so Indian visitors see exactly what they saw before.
 *
 * Opt in with:
 *   <strong data-price-inr="1499" data-ppp="true">&#8377;1499</strong>   one price
 *   <section data-localize-inr>...&#8377;9,999...</section>              every INR amount inside
 */
(function () {
  'use strict';
  function qmLog() {}
  var userCountryCode = null;
  var exchangeRatesCache = null;
  var exchangeRatesTimestamp = null;
  var RATES_CACHE_DURATION = 3600000;
  var RATES_CACHE_KEY = 'qm_exchange_rates';

${core.split('\n').map(l => l ? '  ' + l : l).join('\n')}

  // ---- page scanning -------------------------------------------------------
  var ROOT_SELECTOR = '[data-localize-inr], #bundle-v2-content, #bundle-proof, .bundle-price-note, #bundle-final-price';
  var INR_RE = /\\u20B9\\s?([0-9][0-9,]*(?:\\.[0-9]+)?)/g;
  var country = null;
  var busy = false;
  var again = false;

  async function localizeAmount(amountInr, ppp) {
    var p = await convertPrice(amountInr, country, ppp);
    if (!p || !p.currency || p.currency.code === 'INR') return null;
    return formatPrice(p);
  }

  async function localizeTextNode(node, ppp) {
    var text = node.nodeValue;
    if (!text || text.indexOf('\\u20B9') === -1) return;
    var matches = [];
    text.replace(INR_RE, function (m, num, idx) { matches.push({ m: m, num: num, idx: idx }); return m; });
    if (!matches.length) return;
    var out = '', last = 0;
    for (var k = 0; k < matches.length; k++) {
      var mm = matches[k];
      var local = await localizeAmount(parseFloat(mm.num.replace(/,/g, '')), ppp);
      out += text.slice(last, mm.idx) + (local || mm.m);
      last = mm.idx + mm.m.length;
    }
    out += text.slice(last);
    if (out !== text) node.nodeValue = out;
  }

  async function localizeAll() {
    if (!country || country === 'IN') return;
    // 1) single prices
    var singles = document.querySelectorAll('[data-price-inr]');
    for (var i = 0; i < singles.length; i++) {
      var el = singles[i];
      var amount = parseFloat(el.getAttribute('data-price-inr'));
      if (!(amount > 0) || el.getAttribute('data-price-done') === country) continue;
      var local = await localizeAmount(amount, el.getAttribute('data-ppp') !== 'false');
      if (local) { el.textContent = local; el.setAttribute('data-price-done', country); }
    }
    // 2) every INR amount inside opted-in containers
    var roots = document.querySelectorAll(ROOT_SELECTOR);
    for (var r = 0; r < roots.length; r++) {
      var root = roots[r];
      var ppp = root.getAttribute('data-ppp') !== 'false';
      var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
      var nodes = [];
      while (walker.nextNode()) {
        var n = walker.currentNode;
        var tag = n.parentNode && n.parentNode.nodeName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') continue;
        if (n.nodeValue && n.nodeValue.indexOf('\\u20B9') !== -1) nodes.push(n);
      }
      for (var j = 0; j < nodes.length; j++) await localizeTextNode(nodes[j], ppp);
    }
  }

  function schedule() {
    if (busy) { again = true; return; }
    busy = true;
    localizeAll().catch(function () {}).then(function () {
      busy = false;
      if (again) { again = false; schedule(); }
    });
  }

  async function start() {
    try {
      country = window.userCountryCode || await getUserCountry();
    } catch (e) { return; }
    country = String(country || '').toUpperCase();
    if (!country || country === 'IN') return; // India / unknown: leave INR untouched
    schedule();
    // Sections injected after load (bundle landing content) are localized as they appear.
    if (window.MutationObserver) {
      var timer = null;
      new MutationObserver(function () {
        clearTimeout(timer);
        timer = setTimeout(schedule, 120);
      }).observe(document.body, { childList: true, subtree: true, characterData: true });
    }
  }

  window.D2QLocalizePrices = schedule;
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
  else start();
})();
`;
}

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('price-localizer.js is out of date: run `node scripts/build-price-localizer.js`'); process.exit(1); }
    console.log('price-localizer.js is up to date');
  } else {
    fs.writeFileSync(OUT, out);
    console.log('wrote price-localizer.js (' + Math.round(out.length / 1024) + ' KB)');
  }
}
module.exports = { build, extractBlock };
